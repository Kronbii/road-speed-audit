"""Markdown tables generated from results/*.json (pasted into the README verbatim)."""

from __future__ import annotations

import json
from pathlib import Path


def _f(x, nd=2):
    return "–" if x is None else f"{x:.{nd}f}"


def _ci(e, k, nd=2):
    v = e.get(k)
    ci = e.get(k + "_ci")
    if v is None:
        return "–"
    return f"{v:.{nd}f} [{ci[0]:.{nd}f}, {ci[1]:.{nd}f}]" if ci else f"{v:.{nd}f}"


def _sweep_table(d, key, label):
    lines = [
        f"| {label} | runs | vehicles | valid % | bias km/h | RMSE km/h | P95 abs km/h [95% CI] | 95% CI coverage |",
        "|---:|---:|---:|---:|---:|---:|---:|---:|",
    ]
    for c in d["conditions"]:
        e = c.get("error_valid_kmh") or {}
        if not c.get("runs"):
            lines.append(
                f"| {c['level'].get(key, c['cond'])} | 0 | – | – | – | – | – (zone not measurable: {c.get('error', '')[:40]}) | – |"
            )
            continue
        lines.append(
            f"| {c['level'].get(key, c['cond'])} | {c['runs']} | {c['gt_vehicles']} | {100 * c['valid_rate']:.0f} | "
            f"{_f(e.get('bias'))} | {_f(e.get('rmse'))} | {_ci(e, 'p95_abs')} | {_f(100 * c['ci95_coverage'], 0) if c.get('ci95_coverage') is not None else '–'} |"
        )
    return "\n".join(lines)


def write_tables(rdir: Path) -> str:
    parts = [
        "<!-- generated by experiments/tables.py from results/*.json; do not edit by hand -->\n"
    ]

    def load(n):
        p = rdir / f"{n}.json"
        return json.loads(p.read_text()) if p.exists() else None

    d = load("e01_baseline")
    if d:
        p = d["pooled"]
        e = p["error_valid_kmh"]
        t = p["tracking"]
        parts.append("### E01 baseline\n")
        parts.append(
            "| metric | value |\n|---|---:|\n"
            f"| simulated runs x duration | {p['runs']} x {d['jobs'][0]['duration']:g} s |\n"
            f"| vehicles crossing the zone | {p['gt_vehicles']} |\n"
            f"| valid speed / review only / rejected only / missed | {p['outcomes']['valid']} / {p['outcomes']['review_only']} / {p['outcomes']['rejected_only']} / {p['outcomes']['missed']} |\n"
            f"| bias (km/h) [95% CI] | {_ci(e, 'bias')} |\n"
            f"| RMSE (km/h) [95% CI] | {_ci(e, 'rmse')} |\n"
            f"| P95 abs error (km/h) [95% CI] | {_ci(e, 'p95_abs')} |\n"
            f"| max abs error (km/h) | {_f(e['max_abs'])} |\n"
            f"| relative error: bias / P95 abs (%) | {_f(d['relative_error_pct']['bias'])} / {_f(d['relative_error_pct']['p95_abs'])} |\n"
            f"| per-vehicle 95% interval covers the truth | {_f(100 * p['ci95_coverage'], 0)} % |\n"
            f"| median stated uncertainty u (km/h) | {_f(p['median_u_kmh'])} |\n"
            f"| false valid records / duplicate valid records | {p['false_valid_records']} / {p['duplicate_valid_records']} |\n"
            f"| ID switches / fragmentations inside the zone | {t['zone_id_switches']} / {t['zone_fragmentations']} |\n"
        )
    for name, key, label in (
        ("e02_distance", "zone_centre_m", "zone centre (m)"),
        ("e03_height", "height_m", "height (m)"),
        ("e04_tilt", "tilt_offset_deg", "tilt offset (deg)"),
        ("e06_fps", "fps", "fps"),
    ):
        d = load(name)
        if d:
            parts.append(f"### {name}: {d['title']}\n")
            parts.append(_sweep_table(d, key, label) + "\n")
    d = load("e05_resolution")
    if d:
        parts.append("### e05_resolution: field of view and resolution (zone 40-70 m)\n")
        lines = [
            "| condition | cm of road per px | valid % | bias km/h | RMSE km/h | P95 abs km/h [95% CI] |",
            "|---|---:|---:|---:|---:|---:|",
        ]
        for c in d["conditions"]:
            e = c.get("error_valid_kmh") or {}
            lab = (
                f"HFOV {c['level']['hfov_deg']:g} deg, 1280 px"
                if c["level"]["series"] == "field of view"
                else f"HFOV 60 deg, {c['level']['width']} px"
            )
            lines.append(
                f"| {lab} | {100 * c['geometry']['gsd_along_m_per_px']:.1f} | {100 * c['valid_rate']:.0f} | {_f(e.get('bias'))} | {_f(e.get('rmse'))} | {_ci(e, 'p95_abs')} |"
            )
        parts.append("\n".join(lines) + "\n")
    d = load("e08_density")
    if d:
        parts.append("### e08_density: traffic, occlusion, tracker ablation\n")
        lines = [
            "| road | flow /lane/h | variant | vehicles | valid % | zone ID sw. + frag. /100 veh | P95 abs km/h | MOTA |",
            "|---|---:|---|---:|---:|---:|---:|---:|",
        ]
        for c in d["conditions"]:
            e = c.get("error_valid_kmh") or {}
            lines.append(
                f"| {c['level']['road']} | {c['level']['flow']} | {c['level']['variant']} | {c['gt_vehicles']} | {100 * c['valid_rate']:.0f} | "
                f"{c['zone_id_switches_per_100_veh'] + c['zone_fragmentations_per_100_veh']:.1f} | {_f(e.get('p95_abs'))} | {_f(c['tracking']['mota'])} |"
            )
        parts.append("\n".join(lines) + "\n")
    d = load("e09_calibration")
    if d:
        parts.append("### e09_calibration: calibration error (per-run bias it induces)\n")
        lines = [
            "| varied | value | simulated calibrations | mean abs run bias % | P95 abs run bias % | per-vehicle CI coverage |",
            "|---|---|---:|---:|---:|---:|",
        ]
        for r in d["rows"]:
            lines.append(
                f"| {r['family']} | {r['value']} | {r['calibrations']} | {_f(r['run_bias_abs_pct_mean'])} | {_f(r['run_bias_abs_pct_p95'])} | "
                f"{_f(100 * r['ci95_coverage'], 0) if r['ci95_coverage'] is not None else '–'} % |"
            )
        parts.append("\n".join(lines) + "\n")
    d = load("e10_v85")
    if d:
        s = d["summary"]
        parts.append("### e10_v85: municipal statistics on synthetic traffic\n")
        lines = [
            "| statistic | runs | mean error | RMSE | max abs error | 95% CI covers truth | mean CI width |",
            "|---|---:|---:|---:|---:|---:|---:|",
        ]
        for k, lab, f in (
            ("mean_kmh", "mean speed (km/h)", 1),
            ("v85_kmh", "V85 (km/h)", 1),
            ("share_over_limit", "share over 50 km/h", 100),
        ):
            x = s[k]
            lines.append(
                f"| {lab} | {x['runs']} | {f * x['mean_error']:.2f} | {f * x['rmse']:.2f} | {f * x['max_abs_error']:.2f} | {100 * x['ci_coverage']:.0f} % | {f * x['mean_ci_width']:.2f} |"
            )
        parts.append(
            "\n".join(lines) + ("\n\nShare over the limit in percentage points.\n" if True else "")
        )
        fl = s["flow_veh_h"]
        parts.append(
            f"Flow: mean count error {fl['count_error_mean']:.2f} vehicles per run (max abs {fl['count_error_abs_max']}), mean relative flow error {fl['mean_relative_error_pct']:.1f} %.\n"
        )
    d = load("e11_robustness")
    if d:
        parts.append("### e11_robustness: imaging conditions\n")
        lines = [
            "| condition | vehicles | valid % | bias km/h | P95 abs km/h | 95% CI coverage |",
            "|---|---:|---:|---:|---:|---:|",
        ]
        for c in d["conditions"]:
            e = c.get("error_valid_kmh") or {}
            lines.append(
                f"| {c['level']['label']} | {c['gt_vehicles']} | {100 * c['valid_rate']:.0f} | {_f(e.get('bias'))} | {_f(e.get('p95_abs'))} | "
                f"{_f(100 * c['ci95_coverage'], 0) if c.get('ci95_coverage') is not None else '–'} % |"
            )
        parts.append("\n".join(lines) + "\n")
    d = load("e12_contact")
    if d:
        parts.append("### e12_contact: reference point on the vehicle\n")
        lines = [
            "| model | vehicles | valid % | bias km/h | RMSE km/h | P95 abs km/h |",
            "|---|---:|---:|---:|---:|---:|",
        ]
        for r in d["rows"]:
            e = r["error_valid_kmh"]
            lines.append(
                f"| {r['model']} | {r['gt_vehicles']} | {100 * r['valid_rate']:.0f} | {_f(e.get('bias'))} | {_f(e.get('rmse'))} | {_f(e.get('p95_abs'))} |"
            )
        parts.append("\n".join(lines) + "\n")
    d = load("e13_probe")
    if d:
        parts.append("### e13_probe: correction from k known-speed passes\n")
        lines = [
            "| case | runs | none | k=1 | k=3 | k=5 | k=10 | k=20 |",
            "|---|---:|---:|---:|---:|---:|---:|---:|",
        ]
        for name, c in d["cases"].items():
            ks = [c["k"].get(str(k), {}).get("run_bias_abs_pct_mean") for k in (1, 3, 5, 10, 20)]
            lines.append(
                f"| {name} | {c['runs']} | {_f(c['uncorrected']['run_bias_abs_pct_mean'])} | "
                + " | ".join(_f(k) for k in ks)
                + " |"
            )
        parts.append("Mean absolute run bias in % of speed.\n\n" + "\n".join(lines) + "\n")
    text = "\n".join(parts)
    (rdir / "tables.md").write_text(text)
    return text
